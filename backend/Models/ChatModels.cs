using MongoDB.Bson;
using MongoDB.Bson.Serialization.Attributes;

namespace Personalities.Api.Models;

[BsonIgnoreExtraElements]
public class ChatSession
{
    [BsonId]
    [BsonRepresentation(BsonType.String)]
    public string Id { get; set; } = Guid.NewGuid().ToString("N");

    public string Title { get; set; } = "New Conversation";
    public bool IsGroupChat { get; set; }

    /// <summary>
    /// Indexed scalar array of participating persona IDs for fast MongoDB multikey index queries.
    /// </summary>
    public List<string> ParticipantPersonaIds { get; set; } = new();

    public List<ChatParticipant> Participants { get; set; } = new();

    /// <summary>
    /// Compressed narrative summary of earlier messages in this session (up to SummarizedUpToIndex)
    /// so the beginning of the conversation is always remembered with O(1) token usage.
    /// </summary>
    public string RollingSummary { get; set; } = string.Empty;

    /// <summary>
    /// Exclusive upper index of Messages already folded into RollingSummary.
    /// </summary>
    public int SummarizedUpToIndex { get; set; }

    /// <summary>
    /// Cumulative tokens spent on background/manual summary compaction calls in this session.
    /// </summary>
    public int CompactionTokensSpent { get; set; }

    /// <summary>
    /// Memory facts extracted during this chat session (also persisted to each Persona's cross-session MemoryFacts vault).
    /// </summary>
    public List<PersonaMemoryFact> MemoryFacts { get; set; } = new();

    public List<ChatMessage> Messages { get; set; } = new();

    public ChatContextMetrics ContextMetrics { get; set; } = new();

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAtUtc { get; set; } = DateTime.UtcNow;
}

[BsonIgnoreExtraElements]
public class ChatParticipant
{
    public string PersonaId { get; set; } = string.Empty;
    public string Name { get; set; } = string.Empty;
    public string AvatarEmoji { get; set; } = "🧑";
    public string SummaryTagline { get; set; } = string.Empty;
}

[BsonIgnoreExtraElements]
public class ChatMessage
{
    public string Id { get; set; } = Guid.NewGuid().ToString("N")[..12];

    /// <summary>
    /// "user" or "assistant"
    /// </summary>
    public string Role { get; set; } = "user";

    public string? PersonaId { get; set; }
    public string? PersonaName { get; set; }
    public string? AvatarEmoji { get; set; }

    /// <summary>
    /// Optional ID of the message (written by User or another Persona) that this message directly replies to.
    /// </summary>
    public string? ReplyToMessageId { get; set; }
    public string? ReplyToSenderName { get; set; }
    public string? ReplyToContentPreview { get; set; }

    public string Content { get; set; } = string.Empty;

    public string ProviderUsed { get; set; } = string.Empty;
    public string ModelUsed { get; set; } = string.Empty;
    public long DurationMs { get; set; }

    /// <summary>
    /// Token length of this message's text content alone.
    /// </summary>
    public int EstimatedTokens { get; set; }

    /// <summary>
    /// Input/prompt tokens consumed by the LLM call that produced this message (for assistant messages).
    /// </summary>
    public int PromptTokens { get; set; }

    /// <summary>
    /// Output/completion tokens generated by the LLM call for this message (for assistant messages).
    /// </summary>
    public int CompletionTokens { get; set; }

    /// <summary>
    /// Total tokens spent for this message (PromptTokens + CompletionTokens for assistant; EstimatedTokens for user).
    /// </summary>
    public int TotalTokens { get; set; }

    /// <summary>
    /// Optional memory fact extracted from this turn and saved to the persona's memory vault.
    /// </summary>
    public PersonaMemoryFact? ExtractedMemoryFact { get; set; }

    public bool HasError { get; set; }
    public string? WarningMessage { get; set; }

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
}

[BsonIgnoreExtraElements]
public class ChatContextMetrics
{
    public int TotalMessageCount { get; set; }
    public int ActiveWindowCount { get; set; }
    public int CompactedMessageCount { get; set; }
    public int EstimatedPromptTokens { get; set; }
    public int RawUncompressedTokens { get; set; }
    public int SavedPercentage { get; set; }

    /// <summary>
    /// Cumulative prompt/input tokens spent across all LLM turns in this chat session.
    /// </summary>
    public int SessionPromptTokensSpent { get; set; }

    /// <summary>
    /// Cumulative completion/output tokens spent across all LLM turns in this chat session.
    /// </summary>
    public int SessionCompletionTokensSpent { get; set; }

    /// <summary>
    /// Cumulative total tokens (input + output + compaction) spent in this chat session.
    /// </summary>
    public int SessionTotalTokensSpent { get; set; }
}

public class CreateChatSessionRequest
{
    public List<string> PersonaIds { get; set; } = new();
    public string? Title { get; set; }
}

public class SendChatMessageRequest
{
    /// <summary>
    /// Optional user message text. May be empty when ReplyToMessageId is set and the user wants
    /// Persona B to reply directly to Persona A's message without inserting a new user message.
    /// </summary>
    public string Content { get; set; } = string.Empty;

    /// <summary>
    /// Optional specific message ID in the conversation that the selected persona(s) should reply to.
    /// </summary>
    public string? ReplyToMessageId { get; set; }

    /// <summary>
    /// Optional subset of participant persona IDs that should reply in this turn.
    /// If empty or null, all participants (excluding the author of ReplyToMessageId if Content is empty) reply.
    /// </summary>
    public List<string>? TargetPersonaIds { get; set; }

    public string? Provider { get; set; }
    public string? Model { get; set; }
    public string? ApiKeyOverride { get; set; }
}

public class CompactChatSessionRequest
{
    public string? Provider { get; set; }
    public string? Model { get; set; }
    public string? ApiKeyOverride { get; set; }
}

public class ChatTurnError
{
    public string PersonaId { get; set; } = string.Empty;
    public string PersonaName { get; set; } = string.Empty;
    public string AvatarEmoji { get; set; } = "🧑";
    public string Provider { get; set; } = string.Empty;
    public string Model { get; set; } = string.Empty;
    public string ErrorMessage { get; set; } = string.Empty;
}

public class ChatMessageTurnResponse
{
    public ChatSession Session { get; set; } = new();
    public List<ChatMessage> NewMessages { get; set; } = new();
    public List<PersonaMemoryFact> NewlyLearnedFacts { get; set; } = new();
    public List<ChatTurnError> Errors { get; set; } = new();
}
